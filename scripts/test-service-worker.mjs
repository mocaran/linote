import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const listeners = new Map();
const entries = new Map();
let online = true;
const cache = {put:async (key,response)=>entries.set(String(key.url||key),response),match:async key=>entries.get(String(key.url||key))};
const caches = {open:async()=>cache,match:cache.match,keys:async()=>['linote-shell-v1.21'],delete:async()=>true};
const self = {location:{origin:'https://linote.test'},addEventListener:(name,fn)=>listeners.set(name,fn),skipWaiting:async()=>{},clients:{claim:async()=>{}}};
const fetch = async request => {if (!online) throw new TypeError('offline');return new Response('asset:'+String(request.url||request),{status:200})};
vm.runInNewContext(fs.readFileSync(new URL('../public/sw.js',import.meta.url),'utf8'),{self,caches,fetch,Response,URL,AbortSignal,Promise});
let install;
listeners.get('install')({waitUntil:value=>install=value});
await install;
for (const path of ['/offline.html','/app.js?v=1.21','/styles.css?v=1.21','/overrides.css?v=1.21','/features.css?v=1.21']) assert.ok(entries.has(path),'core asset cached: '+path);
online=false;
let navigation;
listeners.get('fetch')({request:{method:'GET',url:'https://linote.test/',mode:'navigate'},respondWith:value=>navigation=value});
const response=await navigation;
assert.equal(await response.text(),'asset:/offline.html');
console.log('Desktop offline shell check passed');
